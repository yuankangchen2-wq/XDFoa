-- SCRM 线索管理一期 初始化表结构（GORM AutoMigrate 会自动执行，本文件仅作文档与手工初始化参考）
-- 数据库：oa_crm（与其他 CRM 服务共用）

CREATE TABLE IF NOT EXISTS scrm_activity (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tenant_id VARCHAR(64) DEFAULT 'default',
  name VARCHAR(256),
  source_system VARCHAR(64),
  category VARCHAR(64),
  type VARCHAR(64),
  target_object VARCHAR(64),
  intention_dept VARCHAR(128),
  intention_project VARCHAR(128),
  start_time DATETIME NULL,
  end_time DATETIME NULL,
  remark VARCHAR(1024),
  external_id VARCHAR(64),
  code VARCHAR(64),
  status TINYINT DEFAULT 0 COMMENT '0未开始 1进行中 2已结束',
  creator VARCHAR(64),
  creator_dept VARCHAR(128),
  created_at DATETIME,
  updated_at DATETIME,
  INDEX idx_act_name (name),
  INDEX idx_act_code (code),
  INDEX idx_act_ext (external_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS scrm_lead (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tenant_id VARCHAR(64) DEFAULT 'default',
  code VARCHAR(64),
  name VARCHAR(64),
  phone VARCHAR(32),
  student_no VARCHAR(64),
  student_id VARCHAR(64),
  student_tag VARCHAR(64),
  new_old_type VARCHAR(32),
  school VARCHAR(128),
  grade VARCHAR(32),
  district VARCHAR(64),
  campus_code VARCHAR(64),
  lead_type VARCHAR(64),
  enter_type VARCHAR(32) COMMENT '纯新线索/激活线索',
  status VARCHAR(32),
  withdraw_status VARCHAR(32),
  intention_level VARCHAR(32),
  intention_grade VARCHAR(32),
  intention_dept VARCHAR(128),
  intention_project VARCHAR(128),
  intention_campus VARCHAR(128),
  intention_subject VARCHAR(64),
  channel_l1 VARCHAR(64),
  channel_l2 VARCHAR(64),
  channel_l3 VARCHAR(64),
  business_channel VARCHAR(64),
  system_source VARCHAR(64),
  create_method VARCHAR(64),
  activity_id BIGINT,
  activity_name VARCHAR(256),
  task_id BIGINT,
  task_name VARCHAR(256),
  task_type VARCHAR(64),
  owner_id VARCHAR(64),
  owner_name VARCHAR(64),
  owner_dept VARCHAR(128),
  assign_time DATETIME NULL,
  handover_time DATETIME NULL,
  last_follow_at DATETIME NULL,
  last_follow_content VARCHAR(1024),
  follow_count INT DEFAULT 0,
  next_follow_at DATETIME NULL,
  archive_time DATETIME NULL,
  archive_rule VARCHAR(128),
  archive_way VARCHAR(64),
  is_duplicate TINYINT DEFAULT 0,
  creator VARCHAR(64),
  creator_dept VARCHAR(128),
  recommender VARCHAR(64),
  remark VARCHAR(1024),
  import_type VARCHAR(64),
  enter_way VARCHAR(64),
  created_at DATETIME,
  updated_at DATETIME,
  INDEX idx_lead_status (status),
  INDEX idx_lead_phone (phone),
  INDEX idx_lead_code (code),
  INDEX idx_lead_activity (activity_id),
  INDEX idx_lead_owner (owner_id),
  INDEX idx_lead_next_follow (next_follow_at),
  INDEX idx_lead_dup (is_duplicate)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS scrm_import_task (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tenant_id VARCHAR(64) DEFAULT 'default',
  task_name VARCHAR(256),
  is_template TINYINT DEFAULT 0,
  activity_id BIGINT,
  activity_name VARCHAR(256),
  import_method VARCHAR(32),
  data_source VARCHAR(64),
  channel_l1 VARCHAR(64),
  channel_l2 VARCHAR(64),
  channel_l3 VARCHAR(64),
  submit_type VARCHAR(32),
  as_opportunity TINYINT DEFAULT 0,
  dedup_config TEXT,
  operator VARCHAR(64),
  serial_no VARCHAR(64),
  batch_no VARCHAR(64),
  status VARCHAR(32),
  file_name VARCHAR(256),
  total_count INT DEFAULT 0,
  success_count INT DEFAULT 0,
  new_count INT DEFAULT 0,
  active_count INT DEFAULT 0,
  fail_count INT DEFAULT 0,
  duplicate_count INT DEFAULT 0,
  invalid_count INT DEFAULT 0,
  uniqueness_fail_count INT DEFAULT 0,
  dedup_hit_count INT DEFAULT 0,
  dedup_condition_count INT DEFAULT 0,
  dedup_details TEXT,
  fail_rows LONGTEXT,
  deadline DATETIME NULL,
  started_at DATETIME NULL,
  finished_at DATETIME NULL,
  created_at DATETIME,
  updated_at DATETIME,
  INDEX idx_task_serial (serial_no),
  INDEX idx_task_batch (batch_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS scrm_data_record (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tenant_id VARCHAR(64) DEFAULT 'default',
  import_task_id BIGINT,
  related_name VARCHAR(64),
  related_phone VARCHAR(32),
  related_student_no VARCHAR(64),
  activity_student_name VARCHAR(64),
  activity_phone VARCHAR(32),
  import_type VARCHAR(64),
  activity_grade VARCHAR(32),
  related_grade VARCHAR(32),
  enter_way VARCHAR(64),
  lead_enter_type VARCHAR(64),
  fail_reason VARCHAR(1024),
  channel_l1 VARCHAR(64),
  channel_l2 VARCHAR(64),
  channel_l3 VARCHAR(64),
  activity_name VARCHAR(256),
  intention_dept VARCHAR(128),
  intention_project VARCHAR(128),
  owner_name VARCHAR(64),
  handled TINYINT DEFAULT 0,
  created_at DATETIME,
  INDEX idx_rec_task (import_task_id),
  INDEX idx_rec_name (related_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS scrm_exception_lead (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tenant_id VARCHAR(64) DEFAULT 'default',
  related_name VARCHAR(64),
  related_phone VARCHAR(32),
  related_student_no VARCHAR(64),
  activity_student_name VARCHAR(64),
  activity_phone VARCHAR(32),
  channel_l1 VARCHAR(64),
  channel_l2 VARCHAR(64),
  channel_l3 VARCHAR(64),
  system_source_l1 VARCHAR(64),
  system_source_l2 VARCHAR(64),
  activity_name VARCHAR(256),
  data_remark VARCHAR(1024),
  intention_dept VARCHAR(128),
  intention_project VARCHAR(128),
  status VARCHAR(32) DEFAULT '待处理',
  created_at DATETIME,
  updated_at DATETIME,
  INDEX idx_exc_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS scrm_handover_record (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tenant_id VARCHAR(64) DEFAULT 'default',
  biz_type VARCHAR(32),
  biz_ids VARCHAR(512),
  action VARCHAR(64),
  from_owner VARCHAR(64),
  to_owner VARCHAR(64),
  operator VARCHAR(64),
  detail VARCHAR(1024),
  created_at DATETIME
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS scrm_schedule (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tenant_id VARCHAR(64) DEFAULT 'default',
  user_id VARCHAR(64),
  title VARCHAR(256),
  type VARCHAR(32),
  status VARCHAR(32),
  event_date DATETIME,
  event_time VARCHAR(16),
  created_at DATETIME,
  INDEX idx_sched_user_date (user_id, event_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS scrm_consultant_perf (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tenant_id VARCHAR(64) DEFAULT 'default',
  month VARCHAR(7),
  campus VARCHAR(64),
  user_id VARCHAR(64),
  name VARCHAR(64),
  deal_amount DECIMAL(18,2),
  deal_persons INT,
  deal_visits INT,
  INDEX idx_perf_month_campus (month, campus)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS scrm_todo_seed (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  tenant_id VARCHAR(64) DEFAULT 'default',
  role VARCHAR(32),
  todo_key VARCHAR(64),
  count INT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
